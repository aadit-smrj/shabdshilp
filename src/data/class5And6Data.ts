function buildTopicStoreSet(
  wsId: string,
  grade: 'कक्षा 5' | 'कक्षा 6',
  slices: Array<{ topicId: string; count: number; nameHindi: string; nameEnglish: string }>
): QuizQuestion[] {
  const combined: QuizQuestion[] = [];
  const seen = new Set<string>();
  const targetTotal = slices.reduce((sum, s) => sum + s.count, 0);

  slices.forEach((s) => {
    const qs = getUniqueWorksheetQuestions(
      s.topicId,
      s.count + combined.length + 10,
      s.nameHindi,
      s.nameEnglish,
      [],
      grade
    );
    let addedForSlice = 0;
    for (const q of qs) {
      if (addedForSlice >= s.count) break;
      const key = normalizeQuestionKey(q.questionHindi);
      if (!key || seen.has(key)) continue;
      seen.add(key);
      combined.push({
        ...q,
        id: `${wsId}_q_${combined.length + 1}`,
      });
      addedForSlice += 1;
    }
  });

  if (combined.length < targetTotal) {
    const extra = getUniqueWorksheetQuestions(
      'mixed_board',
      targetTotal + 15,
      `${grade} व्याकरण`,
      `${grade} Grammar`,
      [],
      grade
    );
    for (const q of extra) {
      if (combined.length >= targetTotal) break;
      const key = normalizeQuestionKey(q.questionHindi);
      if (!key || seen.has(key)) continue;
      seen.add(key);
      combined.push({
        ...q,
        id: `${wsId}_q_${combined.length + 1}`,
      });
    }
  }

  return combined;
}

